const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.CF_BASE_URL || 'http://127.0.0.1:8000';
fs.mkdirSync('UDF/output', {recursive: true});
(async () => {
  const browser = await chromium.launch({headless: true});
  try {
    const page = await browser.newPage({viewport: {width: 1600, height: 1100}}), errors = [];
    let payload;
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', async response => {if (response.url().endsWith('/api/v2/preview') && response.ok()) payload = await response.json();});
    await page.goto(`${base}/studio`, {waitUntil: 'networkidle'});
    await page.waitForFunction(() => document.querySelector('[data-preview-state]').textContent === '已同步');
    assert.ok(payload);
    assert.equal(payload.validation.status, 'valid');
    assert.equal(payload.validation.issues.some(item => ['curvature_gradient', 'curvature_spike'].includes(item.code)), false);
    assert.ok(payload.validation.metrics.max_abs_curvature_gradient > 50000, 'Retain high numerical values rather than hiding them');
    assert.equal(await page.locator('[data-geometry-issues]').isVisible(), false);
    assert.equal(await page.locator('[data-validation-status]').textContent(), '几何有效');
    await page.locator('.studio-diagnostics summary').first().click();
    await page.locator('[data-analysis=gradient]').click();
    await page.waitForFunction(() => document.querySelector('#analysis-chart')?._fullLayout?.yaxis.title.text.includes('曲率梯度'));
    assert.equal(await page.locator('[data-analysis-interior]').isChecked(), true);
    const gradient = await page.locator('#analysis-chart').evaluate(node => ({length: node._fullData[0].x.length, peak: node._fullData.at(-1).y[0], shapes: node._fullLayout.shapes.map(shape => shape.y0)}));
    const margin = Math.max(6, Math.floor(payload.analysis.suction_s.length * .05));
    assert.equal(gradient.length, payload.analysis.suction_s.length - 2 * margin);
    const metric = payload.validation.metrics.max_abs_curvature_gradient;
    assert.ok(Math.abs(Math.abs(gradient.peak) - metric) < Math.max(1e-8, metric * 1e-12));
    assert.deepEqual(gradient.shapes, []);
    assert.match(await page.locator('[data-analysis-help]').textContent(), /不设固定曲率或梯度上限/);
    assert.match(await page.locator('[data-analysis-summary]').textContent(), /内部峰值/);
    await page.screenshot({path: 'UDF/output/geometry-diagnostics-no-limit.png', fullPage: true});
    await page.locator('[data-analysis-interior]').uncheck();
    await page.waitForFunction(length => document.querySelector('#analysis-chart')._fullData[0].x.length === length, payload.analysis.suction_s.length);
    await page.locator('[data-analysis=curvature]').click();
    await page.waitForFunction(() => document.querySelector('#analysis-chart')._fullLayout.yaxis.title.text === '归一化曲率 κc');
    assert.match(await page.locator('[data-analysis-help]').textContent(), /正负只表示弯曲方向/);
    await page.locator('[data-analysis=angle]').click();
    await page.waitForFunction(() => document.querySelector('#analysis-chart')._fullLayout.yaxis.title.text.includes('金属线角度'));
    assert.match(await page.locator('[data-analysis-help]').textContent(), /不是进口\/出口气流角/);
    assert.match(await page.locator('[data-analysis-summary]').textContent(), /进口 55°，出口 30°/);
    assert.equal(await page.locator('[data-analysis-controls]').isVisible(), false);
    await page.locator('[data-analysis=thickness]').click();
    await page.waitForFunction(() => document.querySelector('#analysis-chart')._fullLayout.yaxis.title.text === '厚度 t/c');
    assert.match(await page.locator('[data-analysis-help]').textContent(), /始终为正/);
    await page.setViewportSize({width: 390, height: 844});
    await page.locator('[data-analysis=gradient]').click();
    await page.waitForFunction(() => document.querySelector('#analysis-chart')._fullLayout.yaxis.title.text.includes('曲率梯度'));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false);
    assert.deepEqual(errors, []);
    console.log('PASS: no fixed curvature warning/threshold lines, real metrics retained, backend-matched peak, full curve toggle, chart guides, mobile');
  } finally {await browser.close();}
})().catch(error => {console.error(error); process.exit(1);});
